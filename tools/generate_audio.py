"""Original synthesized effects and a looping western-inspired demo score."""
from pathlib import Path
import numpy as np,wave,math
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'game/assets/audio';OUT.mkdir(parents=True,exist_ok=True)
SR=44100;rng=np.random.default_rng(4772)
def write(name,x):
    x=np.asarray(x);x=np.tanh(x*.8);x*=.78/max(.78,np.max(np.abs(x)))
    x[:min(200,len(x))]*=np.linspace(0,1,min(200,len(x)))
    x[-min(600,len(x)):]*=np.linspace(1,0,min(600,len(x)))
    pcm=(x*32767).astype('<i2')
    with wave.open(str(OUT/(name+'.wav')),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(SR);w.writeframes(pcm.tobytes())
def tone(freq,duration,decay=7):
    t=np.arange(round(duration*SR))/SR
    return np.sin(2*np.pi*freq*t)*np.exp(-decay*t)
def noise(duration,decay):
    t=np.arange(round(duration*SR))/SR
    return rng.uniform(-1,1,len(t))*np.exp(-decay*t)
def sweep(a,b,duration):
    t=np.arange(round(duration*SR))/SR
    return np.sin(2*np.pi*(a*t+(b-a)/(2*duration)*t*t))*np.exp(-t/duration*4)
def chord(freqs,duration):return sum(tone(f,duration,3) for f in freqs)/len(freqs)
write('shot',noise(.28,35)*.9+sweep(160,35,.28)*.8)
write('hit',noise(.14,40)*.4+tone(190,.14,23)*.4)
write('kill',sweep(340,720,.25)*.6+noise(.25,25)*.2)
write('dash',noise(.25,14)*np.sin(np.linspace(0,np.pi,int(.25*SR)))*.65)
write('reload',sum(np.pad(noise(.065,28)*.5,(int(t*SR),int((.6-t-.065)*SR)))[:int(.6*SR)] for t in [0,.18,.40]))
write('perfect',chord([440,660,880],.65))
write('ricochet',sweep(1700,390,.30)*.7)
write('vortex',noise(1.4,2)*.4+sweep(180,65,1.4)*.35)
write('ultimate',chord([110,165,220,440],1.5)*.8+sweep(250,720,1.5)*.3)
write('hurt',sweep(170,60,.32)*.5+noise(.32,15)*.35)
write('explosion',noise(.8,6)*.7+sweep(90,25,.8)*.9)
write('warning',chord([660,830],.30)*.45)
write('pickup',sweep(520,1040,.5)*.5)
write('ui',tone(330,.14,24)*.5)
write('victory',chord([220,330,440,550],2.4)*.9)
write('defeat',chord([110,130.81,164.81],2.0)*.7)
# Eight bars of plucked pentatonic notes, dry kick/snare, bass and a soft whistle.
beat=60/98;length=32*beat;n=round(length*SR);mix=np.zeros(n)
def add(sound,time,gain=1):
    start=round(time*SR);idx=(np.arange(len(sound))+start)%n;np.add.at(mix,idx,sound*gain)
def pluck(freq,duration):
    count=round(duration*SR);period=max(2,round(SR/freq));buffer=rng.uniform(-1,1,period);out=np.zeros(count)
    for i in range(count):
        j=i%period;out[i]=buffer[j];buffer[j]=.495*(buffer[j]+buffer[(j+1)%period])
    return out
scale=[164.81,196,220,246.94,293.66,329.63]
melody=[0,2,3,2,0,1,0,4,3,2,1,0,2,4,5,3]
for i in range(32):
    add(sweep(85,35,.18),i*beat,.25)
    if i%2:add(noise(.10,40),i*beat,.16)
    add(noise(.05,65),(i+.5)*beat,.035)
    bass=[82.41,82.41,110,98][(i//8)%4]
    if i%2==0:add(pluck(bass,.55),i*beat,.32)
    add(pluck(scale[melody[i%16]],.85),(i+.25)*beat,.22)
    if i%4==0:add(tone(scale[melody[i%16]]*2,1.4,2.3),i*beat,.055)
write('badlands_loop',mix)
(OUT/'LICENSE.txt').write_text('Original procedurally synthesized audio for Mustache Massacre. Generated by tools/generate_audio.py. No third-party samples or recordings are used.\n')
print('Generated',len(list(OUT.glob('*.wav'))),'original audio assets')
